"""Public media proxy — serves order item videos/images through HTTPS.

Browsers block mixed-content (http:// MinIO URLs inside an https:// page).
This proxy lets the frontend reference ``/api/v1/media/{token}`` which is
always served over the same HTTPS origin.

Tokens are short-lived (1 h) HMAC-signed payloads containing the item_id.
They are generated by the lookup and order endpoints and never expose S3 keys.
"""

from __future__ import annotations

from fastapi import APIRouter, HTTPException, Response, status
from starlette.concurrency import run_in_threadpool
from sqlalchemy import select

from app.core.security import verify_media_preview_token, verify_media_token
from app.db.models import Order, OrderItem, OrderItemStatus, OrderStatus
from app.db.session import session_scope
from app.services import storage

router = APIRouter(prefix="/media", tags=["media"])


@router.get("/{token}")
async def proxy_media(token: str, thumbnail: bool = False, scene: bool = False) -> Response:
    """Stream an order item's video (or composite image) from S3."""
    item_id = verify_media_token(token)
    preview = False
    if item_id is None:
        item_id = verify_media_preview_token(token)
        preview = item_id is not None
    if item_id is None:
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, detail="invalid or expired token")

    async with session_scope() as session:
        stmt = select(OrderItem).join(Order).where(OrderItem.id == item_id)
        if not preview:
            stmt = stmt.where(Order.status.in_([OrderStatus.READY, OrderStatus.DELIVERED]),
                              OrderItem.status == OrderItemStatus.READY)
        item = (
            await session.execute(stmt)
        ).scalar_one_or_none()

    if item is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND)

    if scene:
        if not preview:
            raise HTTPException(403, detail="admin preview required")
        if not item.composite_image_s3_key:
            raise HTTPException(404, detail="scene not ready")
        data = await run_in_threadpool(storage.download_bytes, item.composite_image_s3_key)
        return Response(data, media_type="image/png", headers={"Cache-Control": "private, no-store"})

    if thumbnail:
        if not item.thumbnail_s3_key:
            raise HTTPException(status.HTTP_404_NOT_FOUND, detail="thumbnail not ready")
        data = await run_in_threadpool(storage.thumbnail_bytes, item.thumbnail_s3_key)
        return Response(data, media_type="image/webp", headers={"Cache-Control": "private, max-age=3600"})

    is_multi = len(item.character_ids) > 1
    s3_key = item.video_s3_key if item.video_s3_key else (item.composite_image_s3_key if is_multi else None)
    if not s3_key:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="media not ready")

    data = await run_in_threadpool(storage.download_bytes, s3_key)
    is_video = bool(item.video_s3_key)
    content_type = "video/mp4" if is_video else "image/png"
    ext = "mp4" if is_video else "png"
    return Response(
        content=data,
        media_type=content_type,
        headers={
            "Cache-Control": "private, max-age=3600",
            "Content-Disposition": f'inline; filename="video_{item_id}.{ext}"',
        },
    )
